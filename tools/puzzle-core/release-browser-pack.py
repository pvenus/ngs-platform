"""Freeze a locally built browser pack into an NGS release module."""
import base64
import gzip
import hashlib
import json
import re
import sys
from pathlib import Path

pack, output = map(Path, sys.argv[1:])
manifest = (pack / "manifest.json").read_bytes()
spec = json.loads(manifest)
if spec.get("schemaVersion") != "ngs.puzzle-core-pack.v1" or not 1 <= len(spec["files"]) <= 64:
    raise ValueError("invalid puzzle build manifest")
files = {}
total = 0
for entry in spec["files"]:
    name, expected = entry["name"], entry["sha256"]
    if not re.fullmatch(r"[-a-zA-Z0-9_.]{1,160}\.(js|json|wasm|dll)", name) or name in files:
        raise ValueError(f"invalid runtime member: {name}")
    raw = (pack / name).read_bytes()
    total += len(raw)
    if not 1 <= len(raw) <= 6 * 1024 * 1024 or total > 12 * 1024 * 1024:
        raise ValueError(f"runtime size out of bounds: {name}")
    if hashlib.sha256(raw).hexdigest() != expected:
        raise ValueError(f"runtime checksum mismatch: {name}")
    files[name] = [expected, len(raw), base64.b64encode(gzip.compress(raw, mtime=0)).decode("ascii")]
if "dotnet.js" not in files or not any(n.endswith(".wasm") for n in files):
    raise ValueError("missing WebAssembly runtime")
key = hashlib.sha256(manifest).hexdigest()
output.write_text("// Generated by tools/puzzle-core/release-browser-pack.py. Do not edit.\n"
                  + "export const puzzleCoreVersion=" + json.dumps(key) + ";\n"
                  + "export const puzzleCoreFiles=" + json.dumps(files, separators=(",", ":")) + ";\n", encoding="utf-8")
print(f"puzzle-core {key}: {len(files)} files, {total} bytes before compression")
