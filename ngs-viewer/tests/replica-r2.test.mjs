import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdtemp,realpath,rm,readdir} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {createRequire} from 'node:module';
import {openViewerReplica} from '../lib/replica.mjs';
import {pullSpaceToObject} from '../lib/sync.mjs';
import {localProjection} from '../lib/projections.mjs';
const require=createRequire(new URL('../../ngs-local/local-miniflare/package.json',import.meta.url));
const installed=(()=>{try{return Boolean(require.resolve('miniflare'));}catch{return false;}})();
const digest=value=>createHash('sha256').update(value).digest('hex');
test('fresh Viewer uses real Miniflare and protects old paths if a move downloads incompletely',{skip:!installed},async t=>{
 const sandbox=await mkdtemp(join(await realpath(tmpdir()),'viewer-r2-'));
 const root=join(sandbox,'replica');
 const handle=await openViewerReplica(root,{create:true});
 t.after(async()=>{try{await handle.close();}finally{await rm(sandbox,{recursive:true,force:true});}});
 const {replica}=handle;
 assert.deepEqual(await replica.list(),[]);
 let version=new Map([['project.json',Buffer.from('{"title":"비나리"}')],['cinematics/sources/old.png',Buffer.from('old')]]);
 let fault;
 const remote=async path=>{
  if(path==='/api/viewer/manifest')return {status:200,bytes:Buffer.from(JSON.stringify({projectId:'binari',resources:['project','cinematics'],
   files:[...version].map(([path,data])=>({path,size:data.length,sha256:digest(data)}))}))};
  const url=new URL(path,'https://test.invalid'),key=url.searchParams.get('path'),data=version.get(key);
  if(key===fault)return {status:503};
  const start=Number(url.searchParams.get('offset'));
  return {status:200,bytes:data.subarray(start),fileSize:String(data.length),fileSha256:digest(data),fileOffset:String(start)};
 };
 const sync=()=>pullSpaceToObject({replica,remote,parallelism:1});
 const first=await sync();
 assert.equal(first.failed,0);
 assert.equal(first.files,2);
 assert.ok(first.snapshot.version>0);
 const project=await localProjection({root,snapshot:first.snapshot,url:new URL('http://127.0.0.1/api/project-folders'),method:'GET',replica});
 assert.equal((await project.json()).projects[0].name,'비나리');
 version.delete('cinematics/sources/old.png');fault='cinematics/scenes/folder/source.png';version.set(fault,Buffer.from('new'));
 const broken=await sync();
 assert.equal(broken.failed,1);
 assert.equal(broken.snapshot,null);
 assert.ok(await replica.head('cinematics/sources/old.png'));
 fault=null;
 const retry=await sync();
 assert.equal(retry.failed,0);
 assert.equal(retry.removed,1);
 assert.equal(await replica.atVersion(retry.snapshot.version).head('cinematics/sources/old.png'),null);
 assert.ok(await replica.atVersion(first.snapshot.version).head('cinematics/sources/old.png'));
 assert.deepEqual((await readdir(root)).sort(),['miniflare-replica']);
});
